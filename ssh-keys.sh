#!/bin/sh
# Mounts only the SSH keys listed in ssh-keys.conf into herdr and t3, never
# the whole ~/.ssh. Writes compose.override.yaml (docker compose loads
# it automatically) with read-only bind mounts for:
#   - each listed private key (+ its .pub), at the same path as on the host
#   - .ssh-keys/ssh_config: per host, its IdentityFile (IdentitiesOnly), plus
#     HostName/Port/User as resolved by the host's own ssh config (ssh -G)
#   - .ssh-keys/known_hosts: the host's known_hosts entries for those hosts
#     only, so the containers trust exactly the keys the host already trusts
# Re-run after editing ssh-keys.conf, then `docker compose up -d`.
set -eu
cd "$(dirname "$0")"

conf=ssh-keys.conf
out=compose.override.yaml
gen=.ssh-keys
services='herdr t3'
marker='# Generated by ssh-keys.sh from ssh-keys.conf. Edit that and re-run instead.'

warn() { echo "ssh-keys: warning: $*" >&2; }
die() { echo "ssh-keys: $*" >&2; exit 1; }

if [ -e "$out" ] && [ "$(head -n 1 "$out")" != "$marker" ]; then
  die "$out exists and wasn't generated by this script; not overwriting"
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
: > "$tmp/ssh_config"
: > "$tmp/known_hosts"
: > "$tmp/files"
: > "$tmp/hosts"

n=0
if [ -f "$conf" ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    n=$((n + 1))
    line=$(printf '%s' "$line" | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')
    case $line in '' | '#'*) continue ;; esac

    host=${line%%[[:space:]]*}
    key=$(printf '%s' "${line#"$host"}" | sed 's/^[[:space:]]*//')
    at="$conf:$n"
    [ -n "$key" ] || die "$at: expected '<host> <private key>'"

    # Literal host names only: known_hosts entries are looked up by name.
    printf '%s' "$host" | grep -Eq '^[A-Za-z0-9._-]+$' \
      || die "$at: '$host' is not a plain host name (no patterns)"
    grep -qxF "$host" "$tmp/hosts" && die "$at: $host is listed twice"
    printf '%s\n' "$host" >> "$tmp/hosts"

    case $key in "~/"*) key=$HOME/${key#"~/"} ;; esac
    case $key in /*) ;; *) die "$at: key path must be absolute or start with ~/" ;; esac
    case $key in *'"'* | *'\'* | *'$'*) die "$at: unsupported character in $key" ;; esac
    [ -f "$key" ] && [ -r "$key" ] || die "$at: $key: no such readable file"
    # No ssh-agent in the containers, so a passphrase would block git.
    ssh-keygen -y -P '' -f "$key" < /dev/null > /dev/null 2>&1 \
      || warn "$key has a passphrase (or isn't a private key); ssh will prompt for it"

    printf '%s\n' "$key" >> "$tmp/files"
    [ -f "$key.pub" ] && printf '%s\n' "$key.pub" >> "$tmp/files"

    # Resolve the connection details the host would use for this name.
    cfg=$(ssh -G -T "$host" < /dev/null) || die "$at: ssh -G $host failed"
    hostname=$(printf '%s\n' "$cfg" | awk '$1 == "hostname" { print $2; exit }')
    port=$(printf '%s\n' "$cfg" | awk '$1 == "port" { print $2; exit }')
    user=$(printf '%s\n' "$cfg" | awk '$1 == "user" { print $2; exit }')

    {
      echo "Host $host"
      [ "$hostname" = "$host" ] || echo "  HostName $hostname"
      [ "$port" = 22 ] || echo "  Port $port"
      [ "$user" = "$USER" ] || echo "  User $user"
      echo "  IdentityFile \"$key\""
      echo "  IdentitiesOnly yes"
      echo
    } >> "$tmp/ssh_config"

    if [ "$port" = 22 ]; then name=$hostname; else name="[$hostname]:$port"; fi
    if ! ssh-keygen -F "$name" 2> /dev/null | grep -v '^#' >> "$tmp/known_hosts"; then
      warn "no known_hosts entry for $name on this host; run 'ssh $host' here" \
        "once and re-run, or ssh in the containers will ask to trust it"
    fi
  done < "$conf"
fi

if [ ! -s "$tmp/hosts" ]; then
  rm -rf "$out" "$gen"
  echo "ssh-keys: no hosts in $conf; removed $out (no keys mounted)"
  exit 0
fi

mkdir -p "$gen"
mv "$tmp/ssh_config" "$gen/ssh_config"
sort -u "$tmp/known_hosts" > "$gen/known_hosts"
chmod 644 "$gen/ssh_config" "$gen/known_hosts"

mount() {
  printf '      - {type: bind, source: "%s", target: "%s", read_only: true}\n' "$1" "$2"
}
{
  echo "$marker"
  echo "services:"
  first=1
  for svc in $services; do
    echo "  $svc:"
    if [ "$first" = 1 ]; then
      echo "    volumes: &ssh-keys"
      mount "$PWD/$gen/ssh_config" /etc/ssh/ssh_config.d/remote-dev-keys.conf
      mount "$PWD/$gen/known_hosts" /etc/ssh/ssh_known_hosts
      sort -u "$tmp/files" | while IFS= read -r f; do mount "$f" "$f"; done
      first=0
    else
      echo "    volumes: *ssh-keys"
    fi
  done
} > "$out"

echo "ssh-keys: wrote $out for $(wc -l < "$tmp/hosts" | tr -d ' ') host(s):" \
  "$(tr '\n' ' ' < "$tmp/hosts")"
